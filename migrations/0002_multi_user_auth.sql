-- Multi-user authentication, sessions, and per-user data scoping

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
    ON users (LOWER(email));

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_lower
    ON users (LOWER(username));

CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf_token TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_agent TEXT,
    ip_address TEXT
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id
    ON sessions (user_id);

CREATE INDEX IF NOT EXISTS idx_sessions_expires_at
    ON sessions (expires_at);

-- Add nullable user_id columns first so existing single-user data can be migrated cleanly
ALTER TABLE user_progress
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

ALTER TABLE review_logs
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

ALTER TABLE wk_profile
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

ALTER TABLE wk_subjects
    ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

-- If upgrading an existing single-user database that already has rows, attach them to a legacy account
DO $$
DECLARE
    legacy_uid BIGINT;
    has_legacy_rows BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM user_progress WHERE user_id IS NULL
        UNION ALL
        SELECT 1 FROM review_logs WHERE user_id IS NULL
        UNION ALL
        SELECT 1 FROM wk_profile WHERE user_id IS NULL
        UNION ALL
        SELECT 1 FROM wk_subjects WHERE user_id IS NULL
    ) INTO has_legacy_rows;

    IF has_legacy_rows THEN
        SELECT id INTO legacy_uid FROM users WHERE LOWER(email) = 'legacy@bunamateur.local' LIMIT 1;
        IF legacy_uid IS NULL THEN
            INSERT INTO users (email, username, password_hash)
            VALUES ('legacy@bunamateur.local', 'legacy', '!disabled-legacy-account')
            RETURNING id INTO legacy_uid;
        END IF;

        UPDATE user_progress SET user_id = legacy_uid WHERE user_id IS NULL;
        UPDATE review_logs SET user_id = legacy_uid WHERE user_id IS NULL;
        UPDATE wk_profile SET user_id = legacy_uid WHERE user_id IS NULL;
        UPDATE wk_subjects SET user_id = legacy_uid WHERE user_id IS NULL;
    END IF;
END $$;

-- Enforce NOT NULL and rebuild primary keys / indexes scoped by user_id

-- 1. user_progress: PK (user_id, grammar_id)
ALTER TABLE user_progress ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE user_progress DROP CONSTRAINT IF EXISTS user_progress_pkey;
ALTER TABLE user_progress ADD PRIMARY KEY (user_id, grammar_id);

DROP INDEX IF EXISTS idx_user_progress_next_review_at;
DROP INDEX IF EXISTS idx_user_progress_ghost_due_at;
DROP INDEX IF EXISTS idx_user_progress_srs_stage;

CREATE INDEX IF NOT EXISTS idx_user_progress_user_next_review_at
    ON user_progress (user_id, next_review_at)
    WHERE srs_stage > 0 AND srs_stage < 12 AND next_review_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_user_progress_user_ghost_due_at
    ON user_progress (user_id, ghost_due_at)
    WHERE ghost_level > 0 AND ghost_due_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_user_progress_user_srs_stage
    ON user_progress (user_id, srs_stage);

-- 2. review_logs: scoped by user_id
ALTER TABLE review_logs ALTER COLUMN user_id SET NOT NULL;

DROP INDEX IF EXISTS idx_review_logs_reviewed_at;
DROP INDEX IF EXISTS idx_review_logs_grammar_id;

CREATE INDEX IF NOT EXISTS idx_review_logs_user_reviewed_at
    ON review_logs (user_id, reviewed_at DESC);

CREATE INDEX IF NOT EXISTS idx_review_logs_user_grammar_id
    ON review_logs (user_id, grammar_id);

-- 3. wk_profile: PK (user_id), drop legacy singleton id column
ALTER TABLE wk_profile ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE wk_profile DROP CONSTRAINT IF EXISTS wk_profile_pkey;
ALTER TABLE wk_profile DROP CONSTRAINT IF EXISTS wk_profile_id_check;
ALTER TABLE wk_profile DROP COLUMN IF EXISTS id;
ALTER TABLE wk_profile ADD PRIMARY KEY (user_id);

-- 4. wk_subjects: PK (user_id, subject_id)
ALTER TABLE wk_subjects ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE wk_subjects DROP CONSTRAINT IF EXISTS wk_subjects_pkey;
ALTER TABLE wk_subjects ADD PRIMARY KEY (user_id, subject_id);

DROP INDEX IF EXISTS idx_wk_subjects_type;

CREATE INDEX IF NOT EXISTS idx_wk_subjects_user_type
    ON wk_subjects (user_id, subject_type);

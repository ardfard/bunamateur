-- Initial PostgreSQL schema for BunAmateur

CREATE TABLE IF NOT EXISTS grammar_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    reading TEXT NOT NULL,
    meaning TEXT NOT NULL,
    jlpt_level TEXT NOT NULL,
    study_path TEXT NOT NULL,
    structure TEXT NOT NULL,
    nuance TEXT NOT NULL,
    caution TEXT NOT NULL,
    confusable_with TEXT NOT NULL,
    pitch_note TEXT NOT NULL,
    match_patterns TEXT[] NOT NULL DEFAULT '{}'
);

CREATE INDEX IF NOT EXISTS idx_grammar_points_jlpt_level
    ON grammar_points (jlpt_level);

CREATE INDEX IF NOT EXISTS idx_grammar_points_study_path
    ON grammar_points (study_path);

CREATE TABLE IF NOT EXISTS grammar_sentences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grammar_id BIGINT NOT NULL REFERENCES grammar_points(id) ON DELETE CASCADE,
    position INTEGER NOT NULL DEFAULT 0,
    jp_before TEXT NOT NULL,
    jp_after TEXT NOT NULL,
    answer TEXT NOT NULL,
    alt_answers TEXT[] NOT NULL DEFAULT '{}',
    hint TEXT NOT NULL,
    english TEXT NOT NULL,
    nuance_note TEXT NOT NULL,
    UNIQUE (grammar_id, position)
);

CREATE INDEX IF NOT EXISTS idx_grammar_sentences_grammar_id
    ON grammar_sentences (grammar_id);

CREATE TABLE IF NOT EXISTS user_progress (
    grammar_id BIGINT PRIMARY KEY REFERENCES grammar_points(id) ON DELETE CASCADE,
    srs_stage INTEGER NOT NULL DEFAULT 0,
    next_review_at TIMESTAMPTZ,
    ghost_level INTEGER NOT NULL DEFAULT 0,
    ghost_due_at TIMESTAMPTZ,
    correct_count INTEGER NOT NULL DEFAULT 0,
    incorrect_count INTEGER NOT NULL DEFAULT 0,
    streak INTEGER NOT NULL DEFAULT 0,
    user_notes TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_user_progress_next_review_at
    ON user_progress (next_review_at)
    WHERE srs_stage > 0 AND srs_stage < 12 AND next_review_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_user_progress_ghost_due_at
    ON user_progress (ghost_due_at)
    WHERE ghost_level > 0 AND ghost_due_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_user_progress_srs_stage
    ON user_progress (srs_stage);

CREATE TABLE IF NOT EXISTS review_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grammar_id BIGINT NOT NULL REFERENCES grammar_points(id) ON DELETE CASCADE,
    correct BOOLEAN NOT NULL,
    mode TEXT NOT NULL,
    is_ghost BOOLEAN NOT NULL DEFAULT FALSE,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_review_logs_reviewed_at
    ON review_logs (reviewed_at DESC);

CREATE INDEX IF NOT EXISTS idx_review_logs_grammar_id
    ON review_logs (grammar_id);

CREATE TABLE IF NOT EXISTS wk_profile (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    api_token TEXT,
    is_demo BOOLEAN NOT NULL DEFAULT FALSE,
    username TEXT,
    level INTEGER NOT NULL DEFAULT 0,
    lessons_available INTEGER NOT NULL DEFAULT 0,
    reviews_available INTEGER NOT NULL DEFAULT 0,
    smart_furigana BOOLEAN NOT NULL DEFAULT TRUE,
    highlight_known_kanji BOOLEAN NOT NULL DEFAULT TRUE,
    last_synced_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS wk_subjects (
    subject_id BIGINT PRIMARY KEY,
    subject_type TEXT NOT NULL,
    characters TEXT NOT NULL,
    level INTEGER NOT NULL,
    srs_stage INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_wk_subjects_type
    ON wk_subjects (subject_type);

CREATE TABLE IF NOT EXISTS reading_passages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL UNIQUE,
    jlpt_level TEXT NOT NULL,
    topic TEXT NOT NULL,
    content_ruby TEXT NOT NULL,
    english TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_reading_passages_jlpt_level
    ON reading_passages (jlpt_level);

CREATE TABLE IF NOT EXISTS conjugation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dictionary TEXT NOT NULL,
    reading TEXT NOT NULL,
    meaning TEXT NOT NULL,
    word_type TEXT NOT NULL,
    target_form TEXT NOT NULL,
    target_label TEXT NOT NULL,
    answer_kana TEXT NOT NULL,
    answer_kanji TEXT NOT NULL,
    rule_explanation TEXT NOT NULL,
    example_jp TEXT NOT NULL,
    example_en TEXT NOT NULL,
    UNIQUE (dictionary, target_form)
);

CREATE INDEX IF NOT EXISTS idx_conjugation_items_target_form
    ON conjugation_items (target_form);

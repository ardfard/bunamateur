-- v0.2 Account Lifecycle (Password Reset Tokens) & Reading Lab Personal Vocabulary Deck

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id
    ON password_reset_tokens (user_id);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expires_at
    ON password_reset_tokens (expires_at);

CREATE TABLE IF NOT EXISTS user_vocab_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    surface TEXT NOT NULL,
    lemma TEXT NOT NULL,
    reading TEXT NOT NULL DEFAULT '',
    pos TEXT NOT NULL DEFAULT '',
    glosses_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    jlpt TEXT,
    wk_level INTEGER,
    context_sentence TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, lemma)
);

CREATE INDEX IF NOT EXISTS idx_user_vocab_bookmarks_user_created
    ON user_vocab_bookmarks (user_id, created_at DESC);

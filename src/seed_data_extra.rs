/// Returns all grammar points in the curriculum (base + expanded).
pub fn all_seed_grammar() -> Vec<&'static SeedGrammar> {
    let mut all = Vec::with_capacity(crate::seed_data::SEED_GRAMMAR.len() + EXPANDED_SEED_GRAMMAR.len());
    all.extend(crate::seed_data::SEED_GRAMMAR.iter());
    all.extend(EXPANDED_SEED_GRAMMAR.iter());
    all
}

/// Returns all cloze sentences for a grammar point (base sentences + versioned extras).
pub fn sentences_for_grammar(g: &'static SeedGrammar) -> Vec<&'static SeedSentence> {
    let mut out: Vec<&'static SeedSentence> = g.sentences.iter().collect();
    if let Some((_, extras)) = EXTRA_SENTENCES_BY_SLUG
        .iter()
        .find(|(slug, _)| *slug == g.slug)
    {
        out.extend(extras.iter());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn curriculum_has_unique_slugs_and_six_plus_sentences_per_point() {
        let all = all_seed_grammar();
        assert!(all.len() >= 50, "expected 50+ grammar points, got {}", all.len());

        let mut slugs = HashSet::new();
        for g in all {
            assert!(slugs.insert(g.slug), "duplicate grammar slug: {}", g.slug);
            let sents = sentences_for_grammar(g);
            assert!(
                sents.len() >= 6,
                "grammar point '{}' must have at least 6 sentences, got {}",
                g.slug,
                sents.len()
            );
        }
    }
}
